<?php

namespace App\Support;

use Illuminate\Support\Str;

/**
 * **ლექსიკონის ჩანაწერის უნიკალური `key` (აუდიტი 2026-09-14, §B3).**
 *
 * ერთი და იგივე თორმეტხაზიანი ფუნქცია **ცხრა ფაილში** იდო (`VideoType` ·
 * `NoteCategory` · `BookmarkCategory` · `BookGenre` · `GameGenre` ·
 * `SongGenre` · `BoardGameGenre` · `Status` · `Role`) — და ცხრავეს **ერთი
 * და იგივე ბაგი** ჰქონდა:
 *
 * ⚠️ **უნიკალურობა სრულ სტრიქონზე მოწმდებოდა, ჭრა კი ციკლის შემდეგ ხდებოდა.**
 * `while (exists($key)) { $key = "{$base}-{$n}"; }` და მხოლოდ ბოლოს
 * `return mb_substr($key, 0, 60)`. შედეგი ორმაგად მცდარი იყო: შემოწმებული
 * გასაღები **არ** იყო ის, რაც ბაზაში ჩაიწერებოდა, ხოლო `-2` სუფიქსი,
 * რომელიც კონფლიქტს აგვარებდა, ჭრისას **მთლიანად იკარგებოდა**.
 *
 * ⚠️ **გაზომილი და არა თეორიული:** სტატუსის სახელს ვალიდაცია 80 სიმბოლომდე
 * უშვებს, 80-სიმბოლოიანი ქართული სახელის `Str::slug` კი **91 სიმბოლოა**
 * (ქართული ტრანსლიტერაციაში `ჩ`→`ch`, `ძ`→`dz`, `ღ`→`gh`). ორი ასეთი
 * სახელი, რომელთა პირველი 60 სიმბოლო ემთხვევა, მეორეზე
 * `unique(user_id, module, key)`-ს არღვევდა → **`QueryException` → 500
 * სრულიად ჩვეულებრივ შენახვაზე**.
 *
 * ⚠️ **სწორი ნიმუში პროექტშივე იდო** — `CustomFields::makeKey()` ჯერ ჭრიდა
 * და მერე ამოწმებდა. ცხრა ასლი უბრალოდ მისგან განცალკევებით დაიწერა;
 * სწორედ ეს არის ის, რასაც დუბლირება აკეთებს.
 */
class DictionaryKey
{
    /** ლექსიკონების `key` სვეტების საერთო სიგრძე (`varchar(60)`) */
    public const MAX_LENGTH = 60;

    /**
     * ⚠️ **ციკლს ჭერი აქვს.** სივრცე პრაქტიკულად ამოუწურავია, მაგრამ
     * უსასრულო `while`, რომელიც ყოველ ბიჯზე ბაზას ეკითხება, ხარვეზის
     * შემთხვევაში სერვერს დაბლოკავდა. ჭერის მიღწევაზე შემთხვევითი
     * სუფიქსი ერთ მცდელობაში წყვეტს საკითხს.
     */
    private const MAX_ATTEMPTS = 200;

    /**
     * სახელიდან უნიკალური გასაღები.
     *
     * ⚠️ **ჭრა ყოველთვის სუფიქსამდეა**: ჯერ ბაზისი იჭრება ისე, რომ სუფიქსი
     * დაეტიოს, და მხოლოდ მერე მოწმდება — ე.ი. `$taken()`-ს **ზუსტად ის**
     * სტრიქონი გადაეცემა, რომელიც ბაზაში ჩაიწერება.
     *
     * @param  callable(string): bool  $taken  დაკავებულია თუ არა ეს გასაღები
     * @param  string  $fallback  რა ერქვას, თუ სახელში ლათინური არაფერი გამოვიდა
     */
    public static function make(
        string $name,
        callable $taken,
        string $fallback = 'item',
        int $max = self::MAX_LENGTH,
        string $separator = '-',
    ): string {
        $base = Str::slug($name, $separator) ?: $fallback;

        $key = mb_substr($base, 0, $max);

        if (! $taken($key)) {
            return $key;
        }

        for ($n = 2; $n < self::MAX_ATTEMPTS; $n++) {
            $suffix = $separator.$n;
            // ⚠️ ბაზისს ზუსტად სუფიქსის ადგილი ეთმობა — თორემ ისევ ის
            // მოხდებოდა, რაც ამ კლასს გააჩენდა: სუფიქსი ჭრაში დაიკარგებოდა
            $key = mb_substr($base, 0, max(1, $max - mb_strlen($suffix))).$suffix;

            if (! $taken($key)) {
                return $key;
            }
        }

        // ჭერს მიღწეული — შემთხვევითი კუდი კონფლიქტს ერთ ბიჯში ხსნის
        $suffix = $separator.Str::lower(Str::random(6));

        return mb_substr($base, 0, max(1, $max - mb_strlen($suffix))).$suffix;
    }
}
