<?php

namespace App\Support;

/**
 * **`LIKE`-ის შაბლონი ერთ ადგილას (Tasks §10.9).**
 *
 * ⚠️ **ეს `GlobalSearch`-ის ორი `private` მეთოდი იყო და მეორე ასლი
 * სწორედ ის დუბლირებაა, რომლის გამოც `DictionaryKey` შეიქმნა.** ჩატის
 * ძებნას ზუსტად იგივე ორი წესი სჭირდება, ე.ი. ან ისინი ამოვიდოდა, ან
 * ერთი დღეს ერთგან escape-ული იქნებოდა და მეორეგან — არა.
 *
 * ⚠️ **escape-ის გარეშე `%` და `_` შაბლონის სინტაქსია**, ე.ი. „50%"-ის
 * ძებნა მთელ ცხრილს აბრუნებდა.
 */
final class Like
{
    /** `%term%` — escape-ულ ტერმინზე აგებული შაბლონი */
    public static function contains(string $term): string
    {
        return '%'.self::escape($term).'%';
    }

    /**
     * `LIKE`-ის სპეციალური სიმბოლოების გაქცევა.
     *
     * ⚠️ თვითონ `\` პირველი უნდა შეიცვალოს, თორემ მომდევნო ჩანაცვლებების
     * დამატებული უკუწილადები ხელახლა გაიქცეოდა.
     */
    public static function escape(string $term): string
    {
        return str_replace(['\\', '%', '_'], ['\\\\', '\%', '\_'], $term);
    }
}
