<?php

namespace App\Support;

/**
 * **სტატუსის ფერების პალიტრა — `c1`…`c12`.**
 *
 * გასაღებები SPA-ს `--status-c1…c12` ცვლადებია (ორივე თემაში თავისი მნიშვნელობით);
 * სერვერი მხოლოდ გასაღებს ინახავს და ფერის hex-ს არ იცნობს.
 *
 * ⚠️ **უფერო სტატუსი აღარ არსებობს.** ფერის გარეშე შექმნილი სტატუსი მენიუში
 * ნაცრისფერი აიქონით იხატებოდა, დანარჩენები კი — ფერადად. ახლა ასეთს ამ
 * კლასიფიკატორის **პირველი თავისუფალი** ფერი ეწერება და ბაზაში ინახება — ე.ი.
 * გადატვირთვაზე არ იცვლება და მეზობელ სტატუსს არ იმეორებს, სანამ პალიტრა არ ამოიწურება.
 */
final class StatusPalette
{
    /** @var list<string> */
    public const KEYS = ['c1', 'c2', 'c3', 'c4', 'c5', 'c6', 'c7', 'c8', 'c9', 'c10', 'c11', 'c12'];

    /**
     * პირველი ფერი, რომელიც ამ კლასიფიკატორში ჯერ არავის აქვს.
     *
     * ⚠️ თორმეტივე დაკავებულია → ფერი წრეზე მიდის (მეცამეტე — ისევ `c1`): უფერო
     * პუნქტს გამეორებული ფერი სჯობს.
     *
     * @param  iterable<string|null>  $used  კლასიფიკატორის დანარჩენი პუნქტების ფერები
     */
    public static function firstFree(iterable $used): string
    {
        $taken = [];
        $count = 0;

        foreach ($used as $color) {
            $count++;

            if (is_string($color) && $color !== '') {
                $taken[$color] = true;
            }
        }

        foreach (self::KEYS as $key) {
            if (! isset($taken[$key])) {
                return $key;
            }
        }

        return self::KEYS[$count % count(self::KEYS)];
    }
}
