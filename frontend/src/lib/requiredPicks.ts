/** ცარიელია? — სამივე შესაძლო „ცარიელი" ერთ კითხვად */
export function isEmptyPick(value: unknown): boolean {
  if (value === null || value === undefined) return true
  if (typeof value === 'string') return value.trim() === ''
  if (Array.isArray(value)) return value.length === 0

  return false
}

/**
 * რომელი ველებია შეუვსებელი — გასაღებები იმავე სახელით, რითაც ფორმა
 * `errors`-ს კითხულობს, ე.ი. პასუხი პირდაპირ `setErrors`-ში ჯდება.
 */
export function missingPicks(picks: Record<string, unknown>): string[] {
  return Object.entries(picks)
    .filter(([, value]) => isEmptyPick(value))
    .map(([key]) => key)
}

/**
 * მზა `errors` ობიექტი ერთი და იმავე შეტყობინებით.
 *
 * ⚠️ ტექსტს **გარედან** იღებს (`t('validation.pickOne')`) და არა შიგნიდან:
 * ეს ფაილი სუფთა ფუნქციებია, i18n-ის იმპორტი მას ტესტირებადობას დაუკარგავდა.
 */
export function pickErrors(picks: Record<string, unknown>, message: string): Record<string, string> {
  return Object.fromEntries(missingPicks(picks).map((key) => [key, message]))
}

