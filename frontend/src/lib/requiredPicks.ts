/**
 * backend-ის შეცდომის გასაღები → **კატალოგის** გასაღები.
 *
 * ⚠️ ორი ჰქვია და ეს შემთხვევითი არაა: შეცდომა სვეტის სახელით ბრუნდება
 * (`genre_id`, `category_id`), კატალოგი კი ველს ეძახის (`genre`,
 * `category`). რვა ფორმას რომ თითო პატარა რუკა ჰქონოდა, ერთი მათგანი
 * პირველივე გადარქმევაზე დაშორდებოდა — ამიტომ რუკა ერთია და გლობალური:
 * ერთი და იგივე შეცდომის გასაღები ყველა მოდულში ერთსა და იმავე ველს
 * ნიშნავს.
 */
const CATALOGUE_KEY: Record<string, string> = {
  genre_id: 'genre',
  genre_ids: 'genres',
  category_id: 'category',
}

export function catalogueKey(errorKey: string): string {
  return CATALOGUE_KEY[errorKey] ?? errorKey
}

/**
 * შეუვსებელი ველებიდან ის, რაც **ფორმაზე არც ჩანს** — ე.ი. მომხმარებელი
 * მას ვერ შეავსებს და წითელ ტექსტსაც ვერ დაინახავს.
 *
 * პასუხი კატალოგის გასაღებებია, რომ გამომძახებელმა `fields.label()`-ით
 * სახელი დაწეროს.
 */
export function hiddenPicks(missing: string[], shows: (key: string) => boolean): string[] {
  return missing.map(catalogueKey).filter((key) => !shows(key))
}
