/** რამდენი პიქსელი „ბორბლისა" = ერთი საფეხური ზუმისა */
export const WHEEL_STEP = 50

/** `deltaMode` 1 = ხაზები (Firefox-ის თაგვი) — პიქსელად */
const LINE_PX = 33

export function createWheelZoom(zoom: (step: 1 | -1, event: WheelEvent) => void, hint: () => void) {
  let acc = 0

  return (event: WheelEvent) => {
    if (!event.ctrlKey) {
      acc = 0
      hint()

      return
    }

    event.preventDefault()
    acc += event.deltaMode === 1 ? event.deltaY * LINE_PX : event.deltaY
    if (Math.abs(acc) < WHEEL_STEP) return

    // ზემოთ (უარყოფითი) — გადიდება
    const step = acc < 0 ? 1 : -1
    acc = 0
    zoom(step, event)
  }
}
