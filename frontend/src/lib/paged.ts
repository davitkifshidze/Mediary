import { useCallback, useEffect, useState } from 'react'

/* ============================================================
   სიების გვერდებად დაყოფა — ფრონტის მხარე.

   ⚠️ **მოდელი: „ერთი გვერდი, რომელიც იზრდება".** `page` ყოველთვის პირველია,
   იზრდება `per_page`. ორი მიზეზი აქვს, ორივე ჩვენი კოდიდან:

   1. **ბადის სექციებად დაჯგუფება** (`defaultGrouping`) და **ფრანჩაიზის
      კლასტერი** ჩატვირთულ სიაზე ითვლება. ნამდვილი „მე-2 გვერდი"
      პრეფიქსს გაწყვეტდა და ჯგუფის ჯამები სიას აღარ დაემთხვეოდა.
   2. TanStack Query-ის ქეშში ერთი ჩანაწერი რჩება და არა n ცალკეული
      გვერდი, ე.ი. ფილტრის შეცვლაზე გასაწმენდიც ერთია.

   ფასი: „მეტის ჩვენებაზე" პრეფიქსი თავიდან მოდის. 60-ჩანაწერიან ბიჯზე ეს
   იაფია, უსასრულო სქროლთან შედარებით კი მისამართიც სუფთა რჩება.
   ============================================================ */

/** ბიჯი — იგივე რიცხვი ბექენდის `Controller::LIST_PER_PAGE`-შია */
const PAGE_SIZE = 60

/** სიის query-პარამეტრები — ყველა მოდულის `Filters` ამას აფართოებს */
export interface ListParams {
  /** რამდენი ჩანაწერი — `useListLimit()`-ის `limit` */
  per_page?: number
  /**
   * ⚠️ **მთელი სია.** მხოლოდ ოთხ გამომძახებელს სჭირდება — `/purge`-ის რიგს,
   * მასობრივ ცვლილებას, ჩანაწერების ამრჩევს და პლეილისტის ავზს. ბადეზე
   * მისი გამოყენება ზუსტად იმ პრობლემას აბრუნებს, რომლისთვისაც ეს დაიწერა.
   */
  all?: boolean
}

export interface Page<T> {
  items: T[]
  /** **გაფილტრული სიის** ჯამი და არა გვერდისა — „მეტის ჩვენება" ამით იცის */
  total: number
}

interface ListPayload<T> {
  data?: T[]
  meta?: { total?: number }
}

/**
 * `{data, meta}` და `{data}` ერთი წაკითხვით.
 *
 * ⚠️ `all=1`-ზე ბექენდი **`meta`-ს არ აბრუნებს** (მთელი სია გვერდი არაა),
 * ამიტომ ჯამი იქ თვითონ სიის სიგრძეა — თორემ „მეტის ჩვენება" უსასრულოდ
 * იდგებოდა ისეთ სიაზე, სადაც უკვე ყველაფერი ჩამოსულია.
 */
export function readPage<T>(payload: ListPayload<T>): Page<T> {
  const items = payload?.data ?? []

  return { items, total: payload?.meta?.total ?? items.length }
}


/**
 * „მეტის ჩვენების" მდგომარეობა.
 *
 * ⚠️ **`resetKey`-ზე ლიმიტი პირველ გვერდს უბრუნდება.** ფილტრის შეცვლის
 * შემდეგ გაზრდილი `per_page` შენარჩუნება ნიშნავდა, რომ სამ ჩანაწერიან
 * შედეგზეც 300 მოთხოვნილიყო — და პირიქით, ვიწრო ფილტრიდან ფართოზე
 * გადასვლისას მომხმარებელი ვერ მიხვდებოდა, რატომ ჩანს ზუსტად იმდენივე.
 */
export function useListLimit(resetKey: string) {
  const [limit, setLimit] = useState(PAGE_SIZE)

  useEffect(() => {
    setLimit(PAGE_SIZE)
  }, [resetKey])

  const showMore = useCallback(() => setLimit((n) => n + PAGE_SIZE), [])

  return { limit, showMore }
}
